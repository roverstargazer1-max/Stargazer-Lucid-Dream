"""Create a fixed-interface subset; the original complete font remains the fallback.

Maintenance only: requires fonttools[woff]. Generated WOFF2/CSS are committed, so
normal blog builds require neither Python nor a font toolchain.
"""
from pathlib import Path
from hashlib import sha256
import json
import io
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen

theme = Path(__file__).resolve().parents[1]
source = theme / 'source/fonts/lxgw-marker-gothic-v1.003.woff2'
target = theme / 'source/fonts/lxgw-marker-ui-v1.woff2'
style = theme / 'source/css/starry/ui-font.css'
paths = list((theme / 'layout').rglob('*.ejs')) + list((theme / 'source/js/starfield').glob('*.js')) + list((theme / 'source/css/starry').glob('*.css'))
text = ''.join(path.read_text() for path in paths if path != style)
original = TTFont(source)
cmap = original.getBestCmap()
characters = set(range(0x20, 0x7f)) | set(range(0x2000, 0x2070)) | {ord(character) for character in text if ord(character) > 127}
covered = sorted(characters & cmap.keys())
options = subset.Options()
options.flavor = 'woff2'
options.hinting = True
options.glyph_names = True
options.name_IDs = ['*']
options.name_languages = ['*']
options.recalc_timestamp = False
font = subset.load_font(str(source), options)
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=covered)
subsetter.subset(font)
subset.save_font(font, str(target), options)

reopened = TTFont(target)
original_glyphs = original.getGlyphSet()
subset_glyphs = reopened.getGlyphSet()
subset_cmap = reopened.getBestCmap()
assert set(subset_cmap) == set(covered)
for codepoint in covered:
    before = DecomposingRecordingPen(original_glyphs)
    after = DecomposingRecordingPen(subset_glyphs)
    original_glyphs[cmap[codepoint]].draw(before)
    subset_glyphs[subset_cmap[codepoint]].draw(after)
    assert before.value == after.value, f'Outline changed: U+{codepoint:04X}'
    assert original['hmtx'][cmap[codepoint]] == reopened['hmtx'][subset_cmap[codepoint]]
for field in ['ascent', 'descent', 'lineGap']:
    assert getattr(original['hhea'], field) == getattr(reopened['hhea'], field)

ranges = []
for codepoint in covered:
    if ranges and codepoint == ranges[-1][1] + 1:
        ranges[-1][1] = codepoint
    else:
        ranges.append([codepoint, codepoint])
unicode_range = ','.join(f'U+{start:X}' + (f'-{end:X}' if end != start else '') for start, end in ranges)
digest = sha256(target.read_bytes()).hexdigest()
style.write_text("/* Generated by tools/prepare-ui-font.py; original glyphs and metrics retained. */\n@font-face {\n  font-family: 'LXGW Marker Gothic UI';\n  src: url('../../fonts/lxgw-marker-ui-v1.woff2?v=" + digest[:12] + "') format('woff2');\n  font-style: normal; font-weight: 400; font-display: swap;\n  unicode-range: " + unicode_range + ";\n}\n")

# Every original character remains available, including future article titles.
# The browser fetches only the blocks needed by text currently being displayed.
directory = theme / 'source/fonts/lxgw-marker-chunks'
directory.mkdir(exist_ok=True)
chunks = []
rules = []
for block in sorted({codepoint // 256 for codepoint in cmap}):
    points = sorted(codepoint for codepoint in cmap if codepoint // 256 == block)
    chunk = subset.load_font(str(source), options)
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=points)
    worker.subset(chunk)
    output = io.BytesIO()
    chunk.save(output)
    data = output.getvalue()
    checksum = sha256(data).hexdigest()
    filename = f'chunk-{block:04x}-{checksum[:12]}.woff2'
    (directory / filename).write_bytes(data)
    reopened_chunk = TTFont(io.BytesIO(data))
    chunk_cmap = reopened_chunk.getBestCmap()
    glyphs = reopened_chunk.getGlyphSet()
    assert set(chunk_cmap) == set(points)
    for point in points:
        before = DecomposingRecordingPen(original_glyphs)
        after = DecomposingRecordingPen(glyphs)
        original_glyphs[cmap[point]].draw(before)
        glyphs[chunk_cmap[point]].draw(after)
        assert before.value == after.value
        assert original['hmtx'][cmap[point]] == reopened_chunk['hmtx'][chunk_cmap[point]]
    for field in ['ascent', 'descent', 'lineGap']:
        assert getattr(original['hhea'], field) == getattr(reopened_chunk['hhea'], field)
    chunks.append({'block': block, 'path': f'fonts/lxgw-marker-chunks/{filename}', 'bytes': len(data), 'codepoints': len(points)})
    rules.append("@font-face{font-family:'LXGW Marker Gothic';src:url('../../fonts/lxgw-marker-chunks/" + filename + "') format('woff2');font-style:normal;font-weight:400;font-display:swap;unicode-range:U+" + f'{block*256:X}-{block*256+255:X}' + ";}")
(theme / 'source/css/starry/font-chunks.css').write_text('/* Generated font blocks; all original glyphs and metrics retained. */\n' + '\n'.join(rules) + '\n')
manifest = {'sourceSha256': sha256(source.read_bytes()).hexdigest(), 'ui': {'path': 'fonts/lxgw-marker-ui-v1.woff2', 'sha256': digest, 'codepoints': covered}, 'chunks': chunks}
(theme / 'source/fonts/marker-manifest.json').write_text(json.dumps(manifest, separators=(',', ':')) + '\n')
(theme / 'source/js/starfield/font-coverage.js').write_text('// Generated by tools/prepare-ui-font.py.\nexport const uiCodepoints = new Set(' + json.dumps(covered, separators=(',', ':')) + ');\n')
expected_names = {Path(chunk['path']).name for chunk in chunks}
for obsolete in directory.glob('*.woff2'):
    if obsolete.name not in expected_names:
        obsolete.unlink()
print(json.dumps({'sourceBytes': source.stat().st_size, 'subsetBytes': target.stat().st_size, 'coveredCodepoints': len(covered), 'glyphOutlinesAndMetrics': 'identical', 'subsetSha256': digest, 'blocks': len(chunks), 'completeCodepointCoverage': sum(chunk['codepoints'] for chunk in chunks), 'totalChunkBytes': sum(chunk['bytes'] for chunk in chunks)}))
